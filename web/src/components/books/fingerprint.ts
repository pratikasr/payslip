/*
  The service names each account by a fingerprint: the first 8 bytes of SHA-256 over the key's
  canonical encoding (ZIP 316 Revision 2, uvf1 or uvftest1; service/src/viewer.rs fingerprint_of).
  Books computes the same value for a key in that form, so the labels in a key file can be joined
  to the accounts and lines the service returns by fingerprint rather than by position. A key in
  the Revision 0 form (uview1 or uviewtest1) re-encodes differently, so its fingerprint is not
  known here and it is matched by elimination instead (books-data.ts alignKeys).

  A small synchronous SHA-256 (FIPS 180-4) keeps this independent of crypto.subtle, which a page
  served over plain HTTP on a LAN address does not have.
*/

